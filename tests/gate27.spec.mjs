import { expect, test } from '@playwright/test'

test('Gate 27 A/B: 同店同名两行独立发放（金额/收件人/快照各归 Employee.id）', async ({ page }) => {
  await page.goto('/tests/gate27-issue-harness.html')
  await expect(page.getByText('发放工资条', { exact: true })).toBeVisible()
  await expect(page.getByText('稳定计算', { exact: true })).toBeVisible()
  const rows = page.locator('tbody tr')
  await expect(rows).toHaveCount(2)
  const texts = await rows.allInnerTexts()
  const a = texts.find((t) => t.includes('A001'))
  const b = texts.find((t) => t.includes('B001'))
  expect(a).toBeTruthy()
  expect(b).toBeTruthy()
  expect(a).toContain('@user-a')
  expect(b).toContain('@user-b')
  expect(a).toContain('¥1180.00') // 考勤 680 + 调整仅日 500
  expect(b).toContain('¥460.00') // 考勤按实际 6h 计 510 - 调整仅日 50
  // 全选发放
  await page.getByRole('button', { name: '全选' }).click()
  await page.getByRole('button', { name: /确认发放 2 份/ }).click()
  await expect(page.getByText(/已发放 2 份/)).toBeVisible()
  const posted = await page.evaluate(() => window.__posted)
  expect(posted.periodType).toBe('month')
  expect(posted.periodKey).toBe('2026-08')
  expect(posted.rows.length).toBe(2)
  const pa = posted.rows.find((r) => r.employeeId === 'emp-A')
  const pb = posted.rows.find((r) => r.employeeId === 'emp-B')
  expect(pa.employeeName).toBe('张伟')
  expect(pb.employeeName).toBe('张伟')
  expect(pa.totalCents).toBe(118000)
  expect(pb.totalCents).toBe(46000)
  expect(pa.snapshot.summary.total).toBe(1180)
  expect(pb.snapshot.summary.total).toBe(460)
  expect(pa.snapshot.summary.adjustment).toBe(500) // 仅调整日 +500（考勤日无调整）
  expect(pb.snapshot.summary.adjustment).toBe(-50)
  // 快照逐日明细：31 天；统一读取权威 payableHours；仅调整日真实表示（计薪工时 0）
  expect(pa.snapshot.days.length).toBe(31)
  const dayA01 = pa.snapshot.days.find((d) => d.day === '08-01')
  const dayB01 = pb.snapshot.days.find((d) => d.day === '08-01')
  const dayA10 = pa.snapshot.days.find((d) => d.day === '08-10')
  const dayB10 = pb.snapshot.days.find((d) => d.day === '08-10')
  expect(dayA01.payableHours).toBe(8)
  expect(dayA01.hasData).toBe(true)
  expect(dayB01.payableHours).toBe(6)
  expect(dayA10.payableHours).toBe(0)
  expect(dayA10.adjustment).toBe(500)
  expect(dayA10.pay).toBe(500)
  expect(dayB10.adjustment).toBe(-50)
  expect(dayB10.pay).toBe(-50)
})

