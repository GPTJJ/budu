test('Gate 27 J: 竞态——迟到的 8 月响应不得覆盖已选的 7 月状态', async ({ page }) => {
  await page.goto('/tests/gate27-issue-harness.html?race=1')
  // 立即切到 7 月（8 月考勤加载被 mock 延迟 400ms）
  await page.locator('input[type="month"]').fill('2026-07')
  await expect(page.getByText(/该月份暂无可发放的稳定工资数据/)).toBeVisible()
  // 等待迟到的 8 月响应返回后再断言：仍为 7 月状态
  await page.waitForTimeout(700)
  await expect(page.getByText(/该月份暂无可发放的稳定工资数据/)).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(0)
})

