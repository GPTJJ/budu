import { expect, test } from '@playwright/test'

test('合作商供货首页使用任务卡、物流与货款双状态及对账筛选', async ({ page }) => {
  await page.goto('/tests/partner-supply-harness.html')
  await expect(page.getByRole('heading', { name: '合作商供货' })).toBeVisible()
  await expect(page.getByLabel('合作商筛选')).toBeVisible()
  await expect(page.getByLabel('发货门店筛选')).toBeVisible()
  await expect(page.getByLabel('货款筛选')).toBeVisible()
  await expect(page.getByRole('button', { name: '待备货' })).toBeVisible()
  await expect(page.getByRole('button', { name: '已发货' })).toBeVisible()
  await expect(page.locator('span').filter({ hasText: /^部分收款$/ }).first()).toBeVisible()
  await expect(page.locator('span').filter({ hasText: /^已结清$/ }).first()).toBeVisible()
  await expect(page.getByText('供货金额', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /导出对账 Excel/ })).toBeVisible()
})

test('创建供货单默认带出合作商政策并复用分类、搜索、多选与数量编辑', async ({ page }) => {
  await page.goto('/tests/partner-supply-harness.html')
  await page.getByRole('button', { name: /创建供货单/ }).click()
  const sheet = page.getByTestId('partner-supply-create')
  await expect(sheet.getByLabel('合作商')).toHaveValue('partner-qhd')
  await expect(sheet.getByLabel('发货门店')).toHaveValue('guanshe')
  await expect(sheet.getByLabel('合作折扣')).toHaveValue('65')
  await expect(sheet.getByText('合作政策：零售价 × 65%')).toBeVisible()
  await sheet.getByRole('button', { name: '糖果', exact: true }).click()
  await expect(sheet.getByText('NO.1树莓', { exact: true })).toBeVisible()
  await expect(sheet.getByText('NO.2柠檬', { exact: true })).toHaveCount(0)
  await sheet.getByLabel('搜索产品').fill('NO.1')
  await sheet.getByRole('button', { name: /NO\.1树莓/ }).click()
  await sheet.getByLabel('批量设置数量').fill('20')
  await sheet.getByRole('button', { name: '应用到已选' }).click()
  await expect(sheet.getByLabel('NO.1树莓数量')).toHaveValue('20')
  await sheet.getByLabel('NO.1树莓数量').fill('100')
  await expect(sheet.getByText('¥325.00', { exact: true })).toBeVisible()
  await sheet.getByRole('button', { name: '核对并提交' }).click()
  await expect.poll(() => page.evaluate(() => window.__partnerSupplyTest.requests.find((item) => item.type === 'order-create')?.body)).toMatchObject({ partnerId: 'partner-qhd', fromStoreKey: 'guanshe', effectiveDiscountBps: 6500, items: [{ productId: 'p1', quantity: 100 }] })
})

