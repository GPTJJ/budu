test('合作商管理支持新增编辑门店折扣与停用且不提供物理删除', async ({ page }) => {
  await page.goto('/tests/partner-supply-harness.html')
  await page.getByRole('button', { name: /合作商管理/ }).click()
  const manager = page.getByTestId('partner-manager')
  await expect(manager).toContainText('历史供货单 2 张')
  await expect(manager.getByRole('button', { name: /删除/ })).toHaveCount(0)
  await manager.getByRole('button', { name: '新增' }).click()
  await manager.getByText('合作商名称').locator('input').fill('天津合作商')
  await manager.getByText('默认发货门店').locator('select').selectOption('guanshe')
  await manager.getByText('默认合作折扣').locator('input').fill('70')
  await manager.getByRole('button', { name: '保存' }).click()
  await expect.poll(() => page.evaluate(() => window.__partnerSupplyTest.requests.some((item) => item.type === 'partner-create' && item.body.name === '天津合作商'))).toBe(true)
})

test('详情保留冻结价格、逐笔收款、发货留痕并生成正式图片', async ({ page }) => {
  await page.goto('/tests/partner-supply-harness.html')
  await page.getByRole('button', { name: '查看详情' }).first().click()
  const detail = page.getByTestId('partner-supply-detail')
  await expect(detail).toContainText('零售价 ¥5.00 × 65%')
  await expect(detail).toContainText('已收¥200.00')
  await expect(detail).toContainText('待收¥125.00')
  await detail.getByRole('button', { name: '导出图片' }).click()
  await expect.poll(() => page.evaluate(() => window.__partnerSupplyTest.imageExports)).toBeGreaterThan(0)
  await detail.getByRole('button', { name: '登记收款' }).click()
  await page.getByLabel('本次收款').fill('125')
  await page.getByLabel('收款日期').fill('2026-08-29')
  await page.getByRole('button', { name: '确认登记' }).click()
  await expect.poll(() => page.evaluate(() => window.__partnerSupplyTest.requests.find((item) => item.type === 'receipt')?.body.amountCents)).toBe('12500')
  await expect(page.getByTestId('partner-supply-detail')).toContainText('已结清')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByTestId('partner-supply-detail').getByRole('button', { name: '确认发货' }).click()
  await expect(page.getByTestId('partner-supply-detail')).toContainText('已发货')
})

for (const width of [320, 340, 375, 390, 430]) {
  test(`${width}px 首页、创建与详情无横向穿模`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/tests/partner-supply-harness.html')
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0)
    await page.getByRole('button', { name: /创建供货单/ }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0)
    await page.getByRole('button', { name: '关闭弹窗' }).click()
    await page.getByRole('button', { name: '查看详情' }).first().click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0)
  })
}
