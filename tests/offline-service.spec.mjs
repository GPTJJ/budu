test('运单必填、确认去重、运单更正必须原因且不重发', async ({ page }) => {
  await page.goto(entry)
  await expect(page.getByRole('button', { name: '标记已发货', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '发货与顾客提醒' }).click()
  const dialog = page.getByRole('dialog')
  const confirm = dialog.getByRole('button', { name: '确认已发货并通知顾客' })
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel('快递公司', { exact: true }).fill('顺丰速运')
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel('可查件运单号', { exact: true }).fill('SF000000001')
  await confirm.dblclick()
  await expect(dialog.getByText('开发者已确认发货', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.__offlineServiceTest.actions.length)).toBe(1)
  await dialog.getByRole('button', { name: '更正配送信息' }).click()
  await dialog.getByLabel('可查件运单号', { exact: true }).fill('SF000000002')
  await expect(dialog.getByRole('button', { name: '保存更正，不重复提醒' })).toBeDisabled()
  await dialog.getByLabel('更正原因').fill('合成测试：原运单录入错误')
  await dialog.getByRole('button', { name: '保存更正，不重复提醒' }).click()
  await expect(dialog.getByText('配送信息已更正并留痕。不会重复发送提醒。')).toBeVisible()
  expect(await page.evaluate(() => window.__offlineServiceTest.service.notifications.length)).toBe(1)
})

