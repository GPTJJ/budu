test('邮寄长表单在可视高度缩小时仍可滚动确认', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(entry)
  await page.getByRole('button', { name: '发货与顾客提醒' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('快递公司', { exact: true }).fill('顺丰速运')
  await dialog.getByLabel('可查件运单号', { exact: true }).fill('SF000000001')
  await dialog.screenshot({ path: evidencePath(`${testInfo.project.name}-mailing-390.png`) })
  // Browser viewport shrink exercises the overflow contract. It is not a claim
  // that an iPhone's actual software keyboard has been manually verified.
  await page.setViewportSize({ width: 390, height: 430 })
  await dialog.getByRole('button', { name: '确认已发货并通知顾客' }).scrollIntoViewIfNeeded()
  await dialog.getByRole('button', { name: '确认已发货并通知顾客' }).click()
  await expect(dialog.getByText('开发者已确认发货', { exact: true })).toBeVisible()
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
})

test('二维码开关与失败路径明确区分小程序和网页', async ({ page }) => {
  await page.goto(`${entry}?page=qr&qr-off=1`)
  await expect(page.getByTestId('customer-request-qr')).toBeVisible()
  await expect(page.getByText(/小程序入口尚未开启/)).toBeVisible()
  await page.goto(`${entry}?page=qr&qr-error=1`)
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByTestId('customer-request-qr')).toHaveCount(0)
  await page.getByRole('button', { name: '改用网页填写码' }).click()
  await expect(page.getByTestId('customer-request-qr')).toBeVisible()
  await page.goto(`${entry}?page=qr`)
  await expect(page.getByTestId('customer-request-mini-code')).toBeVisible()
  await expect(page.getByText(/体验版 · 仅用于指定测试/)).toBeVisible()
})

test('旧H5开关路径保留门店门禁、配送条件与重新生成取消操作', async ({ page }) => {
  await page.goto(`${entry}?qr-off=1&legacy=1`)
  await expect(page.getByRole('button', { name: '生成顾客填写二维码' })).toBeDisabled()
  await page.getByRole('radiogroup', { name: '类型' }).getByRole('radio', { name: '标准', exact: true }).click()
  await page.getByRole('button', { name: '生成顾客填写二维码' }).click()
  const dialog = page.getByRole('dialog', { name: '顾客填写收件信息' })
  await expect(dialog.getByTestId('customer-request-qr')).toBeVisible()
  await expect(dialog.getByText(/小程序入口尚未开启/)).toBeVisible()
  expect(await page.evaluate(() => window.__offlineServiceTest.qrBodies[0])).toMatchObject({ type: 'MAILING', storeKey: 'xidan', method: '顺丰邮寄', postage: '包邮', shippingTier: 'STANDARD' })
  await dialog.getByRole('button', { name: '重新生成' }).click()
  await expect(dialog.getByTestId('customer-request-qr')).toBeVisible()
  await dialog.getByRole('button', { name: '取消本次二维码' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '标记已发货', exact: true }).click()
  await page.getByRole('dialog', { name: '确认已发货' }).getByRole('button', { name: '确认已发货', exact: true }).click()
  expect(await page.evaluate(() => window.__offlineServiceTest.actions)).toEqual([{ action: 'legacy-ship' }])
  expect(await page.evaluate(() => window.__offlineServiceTest.service.notifications.length)).toBe(0)
})

