import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
mkdirSync(new URL('./offline-service-evidence', import.meta.url), { recursive: true })

const evidencePath = (name) => fileURLToPath(new URL(`./offline-service-evidence/${name}`, import.meta.url))
const entry = '/tests/offline-service-harness.html'
test('接收确认仅新增接收事实；保留待开票与原标记操作', async ({ page }) => {
  await page.goto(`${entry}?page=invoice`)
  await page.getByRole('button', { name: '接收确认与顾客提醒', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '确认收到开票申请' })
  await expect(dialog.getByText('long.synthetic.invoice.address@example.test', { exact: false })).toBeVisible()
  await expect(dialog.locator('input[type=email]')).toHaveCount(0)
  await dialog.getByRole('button', { name: '确认已收到并通知顾客' }).dblclick()
  await expect(dialog.getByText('公司已收到开票申请', { exact: true })).toBeVisible()
  await expect(dialog.getByText('待发送', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.__offlineServiceTest.actions.length)).toBe(1)
  expect(await page.evaluate(() => window.__offlineServiceTest.record.status)).toBe('pending')
  await dialog.getByRole('button', { name: '关闭申请详情' }).click()
  await expect(page.getByRole('button', { name: '标记已开票', exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.classList.contains('budu-overlay-open'))).toBe(false)
})

