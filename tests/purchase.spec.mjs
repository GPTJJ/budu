import { expect, test } from '@playwright/test'

test('采购信息、添加货品与申请列表形成清晰层级', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/tests/purchase-harness.html')
  const information = page.getByTestId('purchase-information')
  await expect(information.getByRole('heading', { name: '采购信息' })).toBeVisible()
  await expect(information.getByLabel('采购门店')).toBeVisible()
  await expect(information.getByLabel('供应商')).toBeVisible()
  await expect(information.getByLabel('预计到货日期')).toBeVisible()
  await expect(page.getByTestId('purchase-item-builder').getByRole('heading', { name: '添加货品' })).toBeVisible()
  await expect(page.getByRole('button', { name: '提交采购申请' })).toBeDisabled()
  const pending = page.locator('[data-purchase-request-id="purchase-pending"]')
  await expect(pending).toContainText('北京测试供应商')
  await expect(pending).toContainText('北京通盈中心店')
  await expect(pending).toContainText('166颗')
  await expect(pending).toContainText('100件')
  await expect(pending.getByRole('button', { name: '收货入库' })).toBeVisible()
  await expect(pending.getByRole('button', { name: '安全删除' })).toHaveClass(/bg-transparent/)
})

