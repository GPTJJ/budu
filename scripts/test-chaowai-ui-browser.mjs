import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { chromium, webkit } from 'playwright-core'

const base = process.env.CHAOWAI_UI_BASE_URL || 'http://127.0.0.1:5217'
const results = []
const outside = []
for (const [name, engine, opts] of [['chrome', chromium, { channel: 'chrome' }], ['webkit', webkit, {}]]) {
  const browser = await engine.launch({ headless: true, ...opts })
  const context = await browser.newContext(name === "webkit" ? { hasTouch: true, userAgent: "Mozilla/5.0 (iPad; CPU OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1" } : {})
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    // All fixture API behavior is in the harness. Unexpected HTTP API requests
    // must not reach any real local service through Vite's proxy.
    if (url.pathname.startsWith('/api/')) return route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: 'SYNTHETIC_HARNESS_ONLY' }) })
    if (['127.0.0.1', 'localhost'].includes(url.hostname) || ['blob:', 'data:'].includes(url.protocol)) return route.continue()
    outside.push(url.origin); return route.abort()
  })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const goto = async (query = '') => { await page.goto(`${base}/tests/chaowai-closure-harness.html?${query}`); await page.waitForFunction(() => Boolean(window.__closure)); await page.waitForTimeout(80) }
  const optionKeys = selector => page.locator(selector).locator('option:not([disabled])').evaluateAll(elements => elements.map(element => element.value))
  const pass = label => { results.push({ browser: name, label, result: 'PASS' }); console.log(name + ': ' + label) }
  try {
    if (process.env.CHAOWAI_UI_SCOPE === 'bootstrap') {
      await goto('page=pos&role=cashier&bound=tongying&bootstrapCashier=1')
      await page.getByLabel('POS 门店').waitFor()
      assert.deepEqual(await optionKeys('[aria-label="POS 门店"]'), ['tongying'])
      const active = await page.evaluate(() => window.__closure.read())
      assert.deepEqual(active.operating.map(row => row.key), ['tongying'])
      assert((await page.evaluate(() => window.__closure.requests)).some(row=>row.path==='/api/userdata'))
      assert((await page.evaluate(() => window.__closure.requests)).some(row=>row.path==='/api/v2/stores'))
      pass('cashier v2门店403时实际PG bootstrap保留绑定营业店与POS')
      await goto('page=pos&role=cashier&bound=chaowai&bootstrapCashier=1')
      await page.getByText('没有可经营门店', { exact: true }).waitFor()
      assert.deepEqual((await page.evaluate(() => window.__closure.read())).operating, [])
      assert.equal((await page.evaluate(() => window.__closure.read())).all.find(row=>row.key==='chaowai').active,false)
      pass('cashier PG bootstrap仍保留关闭身份但不能用于新业务')
      await goto('page=pos&role=cashier&bound=tongying&bootstrapCashier=1&noAuthority=1')
      await page.getByText('没有可经营门店', { exact: true }).waitFor()
      assert.deepEqual((await page.evaluate(() => window.__closure.read())).operating, [])
      pass('cashier不采用缺少权威标记的旧KV门店')
      assert.deepEqual(errors, [])
      pass('cashier实际bootstrap组件无渲染错误')
      continue
    }
    if (process.env.CHAOWAI_UI_SCOPE === 'review') {
      await goto('page=transfer&role=store')
      await page.getByRole('button', { name: /创建调拨/ }).click()
      assert.equal(await page.getByLabel('调入门店', { exact: true }).inputValue(), '')
      assert.equal(await page.getByLabel('调入门店', { exact: true }).isEnabled(), false)
      assert.deepEqual(await optionKeys('[aria-label="调入门店"]'), [''])
      pass('仅绑定闭店账号不默认改挂未授权营业门店')
      await goto('page=transfer&role=store&bound=tongying&empty=1')
      await page.getByRole('button', { name: /创建调拨/ }).click()
      assert.equal(await page.getByLabel('调入门店', { exact: true }).isEnabled(), false)
      await page.evaluate(() => window.__closure.reveal())
      assert.equal(await page.getByLabel('调入门店', { exact: true }).isEnabled(), true)
      await page.getByLabel('调入门店', { exact: true }).selectOption('tongying')
      assert.equal(await page.getByLabel('调入门店', { exact: true }).inputValue(), 'tongying')
      pass('营业状态迟到后单店账号可选本店，不锁死普通调拨入口')
      await goto('page=home&day=month')
      assert.equal(await page.getByRole('button', { name: /北京朝外店/ }).count(), 1)
      await goto('page=home&weekStart=2026-10-12')
      assert.equal(await page.getByRole('button', { name: /北京朝外店/ }).count(), 1)
      await goto('page=home&weekStart=2026-10-19')
      assert.equal(await page.getByRole('button', { name: /北京朝外店/ }).count(), 0)
      pass('实际经营月与闭店当周保留朝外，后续周不列停用店')
      assert.deepEqual(errors, [])
      pass('第二遍复核组件无渲染错误')
      continue
    }
    await goto('page=pos')
    await page.getByLabel('POS 门店').waitFor()
    assert.deepEqual(await optionKeys('[aria-label="POS 门店"]'), ['tongying', 'guanshe', 'xidan'])
    pass('POS 新选择排除朝外')
    await goto('page=pos&open=1')
    await page.getByLabel('POS 门店').selectOption('chaowai')
    await page.getByText('合成商品', { exact: true }).first().click()
    await page.waitForTimeout(40)
    const before = await page.evaluate(() => JSON.stringify(sessionStorage))
    await page.evaluate(() => window.__closure.close())
    assert(!((await optionKeys('[aria-label="POS 门店"]')).includes('chaowai')))
    const checkout = page.getByRole('button', { name: '结算', exact: true }).first()
    assert.equal(await checkout.isEnabled(), false)
    assert.equal(await page.evaluate(() => JSON.stringify(sessionStorage)), before)
    assert.equal((await page.evaluate(() => window.__closure.requests)).filter(row => row.path==='/api/v2/pos/orders' && row.method==='POST').length, 0)
    pass('已打开 POS 停用后拒绝结算、原草稿未改')
    await goto('page=pos&pending=1')
    await page.getByText('朝外店已停止营业，该订单无法继续发起支付，请重新选择门店下单。', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: /现金/ }).first().isEnabled(), false)
    await page.getByRole('button', { name: '继续核对', exact: true }).click()
    assert.equal((await page.evaluate(() => window.__closure.requests)).filter(row => row.path.endsWith('/old-payment/query')).length, 1)
    assert.equal((await page.evaluate(() => window.__closure.requests)).filter(row => row.path.endsWith('/payments') && row.method==='POST').length, 0)
    pass('朝外待付原归属/原查单保留，新支付禁用')
    await goto('page=pos&role=store')
    await page.getByRole('button', { name: '查看历史订单' }).waitFor()
    await page.getByRole('button', { name: '查看历史订单' }).click()
    await page.getByText('SYNTHETIC-1').waitFor()
    pass('只绑定朝外账号仍能读取本人原权限内历史订单')
    await goto('page=transfer')
    await page.getByRole('button', { name: /创建调拨/ }).click()
    assert(!((await optionKeys('[aria-label="调出门店"]')).includes('chaowai')))
    assert(!((await optionKeys('[aria-label="调入门店"]')).includes('chaowai')))
    await page.getByLabel('返回调拨记录').click()
    await page.getByRole('button', { name: /筛选/ }).click()
    assert((await optionKeys('[aria-label="筛选调出门店"]')).includes('chaowai'))
    assert((await optionKeys('[aria-label="筛选调入门店"]')).includes('chaowai'))
    pass('调拨双向新选择排除朝外、历史筛选完整')
    await goto('page=purchase')
    await page.getByLabel('筛选门店').waitFor()
    assert((await optionKeys('[aria-label="筛选门店"]')).includes('chaowai'))
    await page.getByRole('button', { name: '新建备单' }).click()
    assert(!((await optionKeys('[aria-label="收货门店"]')).includes('chaowai')))
    pass('采购新备单排除朝外、历史单过滤保留')
    await goto('page=schedule')
    await page.getByRole('button', { name: '北京朝外店', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '添加排班', exact: true }).count(), 0)
    await page.getByRole('button', { name: '北京通盈中心店', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '添加排班', exact: true }).count(), 7)
    pass('排班历史店可选可读，闭店不可新增，通盈原入口保留')
    await goto('page=entry')
    await page.getByTestId('daily-entry-store').waitFor()
    assert(!((await optionKeys('[data-testid="daily-entry-store"]')).includes('chaowai')))
    assert((await optionKeys('[data-testid="ledger-store-filter"]')).includes('chaowai'))
    pass('普通营业录入排除朝外，历史账本仍可选')
    await goto('page=mailing')
    await page.getByLabel('本次服务门店').waitFor()
    assert(!((await optionKeys('[aria-label="本次服务门店"]')).includes('chaowai')))
    pass('邮寄新服务门店排除朝外')
    await goto('page=home')
    await page.getByRole('button', { name: /门店待录入/ }).click()
    const missing = page.getByRole('dialog', { name: '待录入门店' })
    await missing.waitFor()
    assert.equal(await missing.getByText('北京朝外店', { exact: true }).count(), 0)
    assert.equal(await missing.getByText('北京通盈中心店', { exact: true }).count(), 1)
    pass('当前缺录不催朝外，其他营业门店保留')
    await goto('page=home&day=10-14')
    assert.equal(await page.getByRole('button', { name: /北京朝外店/ }).count(), 0)
    await goto('page=home&day=10-13')
    assert.equal(await page.getByRole('button', { name: /北京朝外店/ }).count(), 1)
    pass('经营日期10/14排除闭店，10/13历史业务门店保留')
    for (const width of [320, 340, 375, 390, 430, 768, 1024]) {
      await page.setViewportSize({ width, height: width >= 768 ? 1024 : 844 })
      await goto('page=pos')
      await page.getByLabel('POS 门店').waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, `POS overflow ${width}`)
      await goto('page=transfer')
      await page.getByRole('button', { name: /创建调拨/ }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, `transfer overflow ${width}`)
      const rect = await page.getByLabel('调出门店').boundingBox()
      assert(rect.x >= 0 && rect.x + rect.width <= width)
      pass(`POS/调拨 ${width}px 无页面/选择器横向溢出`)
    }
    await goto('page=pos&empty=1')
    await page.getByText('没有可经营门店', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('POS 门店').count(), 0)
    pass('未知目录无固定朝外回退')
    assert.deepEqual(errors, [])
    pass('实际组件无浏览器启动或渲染错误')
  } finally { await context.close(); await browser.close() }
}
assert.deepEqual(outside, [])
const summary={ results, passed: results.length, outsideRequests: outside.length, syntheticOnly: true, productionAccess: false }
if(process.env.CHAOWAI_UI_RESULT_PATH) await fs.writeFile(process.env.CHAOWAI_UI_RESULT_PATH,JSON.stringify(summary,null,2)+'\n')
console.log(JSON.stringify(summary,null,2))
